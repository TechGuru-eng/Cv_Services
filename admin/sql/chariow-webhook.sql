CREATE TABLE IF NOT EXISTS chariow_deliveries (
 delivery_id VARCHAR(150) PRIMARY KEY,
 body_hash CHAR(64) NOT NULL,
 received_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS chariow_sales (
 sale_id VARCHAR(100) PRIMARY KEY,
 payload MEDIUMTEXT NOT NULL,
 product_id VARCHAR(100) NOT NULL,
 customer_email VARCHAR(255) NOT NULL,
 amount DECIMAL(12,2) DEFAULT NULL,
 currency VARCHAR(10) NOT NULL,
 order_id INT DEFAULT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'review',
 reason VARCHAR(255) NOT NULL DEFAULT '',
 received_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY sale_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
